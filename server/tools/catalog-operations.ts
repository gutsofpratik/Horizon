/** Resolve familiar catalog labels to real actions, internal behavior or an explicit limitation. */
export function catalogOperation(value:string,registry:ToolRegistry,ctx:ToolContext):any{
 let name=value.trim().toLowerCase();
 // The reference catalog uses both dotted labels (browser.open) and command
 // labels (git status / gh pr create). Accept either without making models
 // guess a second spelling.
 if(/^gh\s+pr\s+/.test(name))name='git.pr_'+name.replace(/^gh\s+pr\s+/,'').replace(/[\s-]+/g,'_');
 else if(/^git\s+/.test(name))name='git.'+name.replace(/^git\s+/,'').replace(/[\s-]+/g,'_');
 else if(!name.includes('.')&&/^(?:task|file|directory|archive|shell|browser|computer|web|data|document|spreadsheet|presentation|http|api|mcp|integration|skill|permission|sandbox|scope|credential|action|execution|result|test|debug|build|code|agent|schedule|trigger|background|notification)\s+/.test(name))name=name.replace(/\s+/,'.').replace(/[\s-]+/g,'_');
 const [family,operation]=name.split('.',2);if(!operation)return null;
 if(direct[name]){const tool=registry.tools.get(direct[name]);if(!tool)return {category:direct[name],available:false,reason:'Tool is not registered'};const reason=tool.available?.(),decision=decideTool(tool,ctx,ctx.app.store.get('settings','main')??{});return {category:direct[name],available:!reason&&decision.allowed,reason:reason??(decision.allowed?null:decision.reason)};}
 if(['artifact.render','browser.use_session'].includes(name))return {category:family,available:false,internal:true,reason:name==='artifact.render'?'The artifact panel renders supported artifacts automatically; create/update the artifact source and use export for downloadable files.':'Authorized browser session state is managed by the browser runtime; open an owned tab and use its observed ID.'};
 if(['http.headers','http.authenticate','mcp.connect','integration.connect'].includes(name))return {category:family==='http'?'http':'mcp',available:false,internal:true,reason:'The user configures and authorizes saved connections in Customize → Connectors; models cannot add destinations or reveal credentials.'};
 let category=families[family],action=aliases[name]??operation;
 if(name==='file.convert'){category='data';action='convert';}
 if(name==='sandbox.execute'){category='shell';action='run';}
 if(name==='integration.invoke'){category='mcp';action='call_tool';}
 if(['test','build','code','debug'].includes(family)){category='shell';action=aliases[name]??'run';}
 const leaves=category?groupLeafNames(category,registry):[];const leaf=leaves.find(item=>groupAction(item)===action);
 if(!leaf){if(internal[family])return {category:category??family,available:false,internal:true,reason:internal[family]};return {category:category??family,action,available:false,reason:`${value} has no implemented action in this runtime. Discover ${category??family} for actual supported tools.`};}
 const tool=registry.tools.get(leaf)!,unavailable=tool.available?.(),decision=decideTool(tool,ctx,ctx.app.store.get('settings','main')??{});
 return {category,action,available:!unavailable&&decision.allowed,reason:unavailable??(decision.allowed?null:decision.reason),suggested_arguments:{action,...defaults[name],...(family==='http'&&operation!=='list_connections'&&operation!=='request'?{method:operation.toUpperCase()}:{})}};
}
